
.MODEL SMALL
.STACK 100H

.DATA
    ARRAY1 DB 1,2,3,4,5,6,7,8
    ARRAY2 DB 8 DUP(?)

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV SI, OFFSET ARRAY1
    MOV DI, OFFSET ARRAY2+7
    MOV CX, 8

COPY:
    MOV AL, [SI]
    MOV [DI], AL

    INC SI
    DEC DI

    DEC CX
    JNZ COPY

    MOV AH, 4CH
    INT 21H

MAIN ENDP
END MAIN

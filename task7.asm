
.MODEL SMALL
.STACK 100H

.DATA
	MSG DB 'ENTER A CHARACTER:$'
	CAPITAL DB 'Capital$'
	SMALL DB 'Small$'
.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX
    MOV AH,09H
    MOV DX,OFFSET MSG
    INT 21H

    MOV AH, 01H
    INT 21H

    CMP AL,'A'
    JL EXIT
    CMP AL,'Z'
    JLE CAPITALL

    CMP AL,'a'
    JL EXIT
    CMP AL,'z'
    JLE SMALLL
	JMP EXIT

CAPITALL:
    MOV AH,09H
    MOV DX, OFFSET CAPITAL
    INT 21H
    JMP EXIT

SMALLL:
    MOV AH,09H
    MOV DX, OFFSET SMALL
    INT 21H
    JMP EXIT

EXIT:

    MOV AH, 4CH
    INT 21H

MAIN ENDP
END MAIN